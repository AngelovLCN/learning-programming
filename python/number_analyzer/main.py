a = int(input("Введите число: "))
print("Ваше число: ", a)

if a > 0:
    print("Ваше число положительное")
elif a < 0:
    print("Ваше число отрицательное") 
else:
    print("Ваше число равно 0")

if a % 2 == 0:
    print("Ваше число четное")
else:
    print("Ваше число НЕ четное")

if a >= 1 and a <=100:
    print("Ваше число входит в диапазон 1-100")
else:
    print("Ваше число НЕ входит в диапазон 1-100")

print("Программа завершена")