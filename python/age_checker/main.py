a = int(input("Введите ваш возраст: "))

if a <= 0:
    print("Неверно введено значение")
elif a < 7:
    print("Вы ребенок")
elif a <= 17:
    print("Вы школьник")
elif a <= 59:
    print("Вы взрослый") 
else:
    print("Вы пенсионер")

if a % 2 == 0 and a >= 1:
    print("Ваш возраст четный")
elif a % 2 == 1 and a >= 1:
    print("Ваш возраст не четный")

print("Программа завершена")